"""Strictly Separated Point-in-Time Historical Outcome Labels Schema.

Defines immutable post-event market response records with full timestamp provenance,
horizon resolution verification, data quality diagnostics, futures contract metadata,
and strict causal maturity enforcement (`outcome_end_price_ts <= query_decision_ts`).
"""

from datetime import datetime, timezone
from enum import Enum
from typing import Any, Dict, Optional
from pydantic import BaseModel, Field

from backend.alpha.historical_store import StoredOutcomeRecord


class OutcomeHorizon(str, Enum):
    """Canonical forward return measurement horizons."""

    M1 = "1m"
    M5 = "5m"
    M30 = "30m"
    H1 = "1h"
    D1 = "1d"
    D5 = "5d"

    @property
    def min_required_resolution_seconds(self) -> float:
        """Maximum allowable bar spacing to support this horizon reliably."""
        return {
            "1m": 60.0,
            "5m": 300.0,
            "30m": 900.0,
            "1h": 1800.0,
            "1d": 86400.0,
            "5d": 86400.0,
        }[self.value]


class OutcomeDataQualityStatus(str, Enum):
    """Audit flags qualifying integrity of computed outcome label."""

    VERIFIED = "VERIFIED"
    INSUFFICIENT_RESOLUTION = "INSUFFICIENT_RESOLUTION"
    MISSING_DATA = "MISSING_DATA"
    STALE_OBSERVATION = "STALE_OBSERVATION"
    HALTED_TRADING = "HALTED_TRADING"
    ROLLOVER_ADJUSTED = "ROLLOVER_ADJUSTED"
    ROLLOVER_INVALID = "ROLLOVER_INVALID"
    CORPORATE_ACTION_ADJUSTED = "CORPORATE_ACTION_ADJUSTED"
    IMMATURE = "IMMATURE"


class PriceObservation(BaseModel):
    """Normalized market observation at a point in time (bar close, trade, or quote mid)."""

    timestamp_utc: datetime
    price: float = Field(..., gt=0.0, description="Observed reference or traded price")
    bid: Optional[float] = None
    ask: Optional[float] = None
    volume: Optional[float] = None
    contract_id: Optional[str] = Field(None, description="Explicit futures expiry/contract identifier if derivative")
    is_halted: bool = False
    corporate_action_factor: float = Field(default=1.0, gt=0.0, description="Cumulative split/bonus adjustment multiplier")
    source_name: str = "LOCAL_HISTORICAL_BARS"


class EventOutcomeLabel(BaseModel):
    """
    Isolated future market response label generated by the Event-Study Engine.
    Contains complete timestamp provenance and strict data-quality gating.
    Must never be merged blindly into live feature vectors without causal maturity checks.
    """

    event_id: str
    instrument_id: str
    horizon: OutcomeHorizon
    event_timestamp_utc: datetime
    decision_timestamp_utc: datetime
    outcome_start_price_ts: Optional[datetime] = None
    outcome_end_price_ts: Optional[datetime] = None

    start_price: Optional[float] = None
    end_price: Optional[float] = None
    raw_log_return: Optional[float] = None
    simple_return: Optional[float] = None

    benchmark_instrument: Optional[str] = None
    benchmark_return: Optional[float] = None
    benchmark_adjusted_return: Optional[float] = None

    realized_volatility: Optional[float] = None
    max_favorable_excursion: Optional[float] = None
    max_adverse_excursion: Optional[float] = None
    avg_spread_bps: Optional[float] = None
    total_volume: Optional[float] = None

    market_data_source: str = "LOCAL_BARS"
    anchor_mode: str = "PRE_EVENT_AS_OF"
    data_quality_status: OutcomeDataQualityStatus = OutcomeDataQualityStatus.VERIFIED
    session_boundary_crossed: bool = False
    overnight_gap_included: bool = False
    contract_rollover_applied: bool = False
    start_contract_id: Optional[str] = None
    end_contract_id: Optional[str] = None
    rollover_metadata: Optional[Dict[str, Any]] = None
    notes: Optional[str] = None
    is_synthetic: bool = False

    def is_matured_at(self, query_decision_ts: datetime) -> bool:
        """
        Causal maturity check: An outcome is strictly unmatured (and prohibited from leaking)
        unless its measurement window completed at or before `query_decision_ts`.
        """
        if self.outcome_end_price_ts is None:
            return False
        return self.outcome_end_price_ts <= query_decision_ts

    def to_stored_outcome_record(self) -> Optional[StoredOutcomeRecord]:
        """Convert to persistent storage schema when valid endpoints exist."""
        if self.outcome_start_price_ts is None or self.outcome_end_price_ts is None:
            return None
        return StoredOutcomeRecord(
            event_id=self.event_id,
            instrument_id=self.instrument_id,
            horizon_label=self.horizon.value,
            outcome_start_ts=self.outcome_start_price_ts,
            outcome_end_ts=self.outcome_end_price_ts,
            return_simple=self.simple_return,
            return_log=self.raw_log_return,
            benchmark_adjusted_return=self.benchmark_adjusted_return,
            benchmark_instrument=self.benchmark_instrument,
            realized_volatility=self.realized_volatility,
            max_favorable_excursion=self.max_favorable_excursion,
            max_adverse_excursion=self.max_adverse_excursion,
            spread_bps_avg=self.avg_spread_bps,
            data_quality_status=self.data_quality_status.value,
            market_data_source=self.market_data_source,
        )
